// keepNUMATypesInUse adds the kept NUMA types to the NUMA types generated by numaTypes, by name, and returns them
// sorted by name (docs/scheduler-numa.md §6.1). In each zone where a NodeClaim uses a NUMA type that the zone does
// not offer for the NodeClaim's capacity type, the type gets an unavailable offering of that capacity type; a NUMA
// type whose slot shape is gone from every zone is rebuilt from its name while a NodeClaim uses it. Karpenter's
// drift asks only for a compatible offering, so those nodes are not replaced, and nothing new launches on them.
// The caller holds the lock.
func (p *DefaultProvider) keepNUMATypesInUse(byName map[string]*InstanceTypeStatic, uses []nodeClaimUse) []*InstanceTypeStatic {
	rebuilt := []string{}

	for _, use := range uses {
		it, ok := byName[use.instanceType]
		if !ok {
			if it = p.keptNUMAType(use.instanceType); it == nil {
				continue
			}

			byName[use.instanceType] = it
			rebuilt = append(rebuilt, it.Name)
		}

		capacityType := lo.Ternary(use.capacityType != "", use.capacityType, it.CapacityType)

		offered := slices.ContainsFunc(it.Offerings, func(o *cloudprovider.Offering) bool {
			return o.Requirements.Get(corev1.LabelTopologyRegion).Has(use.region) &&
				o.Requirements.Get(corev1.LabelTopologyZone).Has(use.zone) &&
				o.Requirements.Get(karpv1.CapacityTypeLabelKey).Has(capacityType)
		})
		if !offered {
			it.Offerings = append(it.Offerings, zoneOffering(it, use.region, use.zone, capacityType, false))
		}
	}

	if len(rebuilt) > 0 {
		p.log.V(1).Info("Keeping NUMA types that NodeClaims still use", "instanceTypes", rebuilt)
	}

	return slices.SortedFunc(maps.Values(byName), func(a, b *InstanceTypeStatic) int {
		return cmp.Compare(a.Name, b.Name)
	})
}

// keptNUMAType is the kept NUMA type name, rebuilt with no offerings from the NUMA template of its family and the
// slot shape read from its name. It is nil when name is a static type or not a name that template generates.
func (p *DefaultProvider) keptNUMAType(name string) *InstanceTypeStatic {
	if p.staticNames[name] {
		return nil
	}

	family, cpus, memoryGB, ok := parseInstanceTypeName(name)
	if !ok {
		return nil
	}

	tmpl, ok := lo.Find(p.numaTemplates, func(t *InstanceTypeStatic) bool { return t.Name == family })
	if !ok {
		return nil
	}

	return newNUMAType(tmpl, name, zonecapacity.SlotShape{Fraction: tmpl.NUMA, CPUs: cpus, Memory: uint64(memoryGB) * zonecapacity.GiB})
}

// numaTypes generates the NUMA types of the templates from the slot shapes of every zone of regions, by name
// (docs/scheduler-numa.md §6). Each distinct (template, slot shape) is one type, named
// <family>.<cpu>VCPU-<memory>GB, offered in the zones that have that shape, and available where
// the zone has a free slot of it. A slot shape with less than 1GiB of memory per vCPU is not offered.
// The caller holds the lock.
func (p *DefaultProvider) numaTypes(regions []string) map[string]*InstanceTypeStatic {
	byName := map[string]*InstanceTypeStatic{}

	taken := map[string]bool{}
	small := map[string]bool{}

	for _, region := range regions {
		for _, zone := range p.cloudCapacityProvider.Zones(region) {
			for _, offer := range p.cloudCapacityProvider.Slots(region, zone) {
				for _, tmpl := range p.numaTemplates {
					if tmpl.NUMA != offer.Shape.Fraction {
						continue
					}

					family := tmpl.Name
					name := numaTypeName(family, offer.Shape)

					if offer.Shape.Memory < uint64(offer.Shape.CPUs)*zonecapacity.GiB {
						if !small[name] {
							small[name] = true

							p.log.Info("NUMA type has less than 1GiB of memory per vCPU, skipping it", "name", name, "template", tmpl.Name)
						}

						continue
					}

					// A static entry keeps its name; the NUMA type of the same name is not offered.
					if p.staticNames[name] {
						if !taken[name] {
							taken[name] = true

							p.log.Info("NUMA type name is taken by a static instance type, skipping it", "name", name, "template", tmpl.Name)
						}

						continue
					}

					it, ok := byName[name]
					if !ok {
						it = newNUMAType(tmpl, name, offer.Shape)
						byName[name] = it
					}

					it.Offerings = append(it.Offerings, zoneOfferings(it, region, zone, offer.Free > 0)...)
				}
			}
		}
	}

	return byName
}

// numaTypeName names the NUMA type of family for a slot shape: <family>.<cpu>VCPU-<memory>GB.
func numaTypeName(family string, shape zonecapacity.SlotShape) string {
	return instanceTypeName(family, shape.CPUs, int(shape.Memory/zonecapacity.GiB))
}

// newNUMAType is the NUMA type of tmpl for a slot shape, with no offerings: the slot's CPUs and
// memory, the template's other capacity, and its overhead, computed from the capacity when the
// template has none.
func newNUMAType(tmpl *InstanceTypeStatic, name string, shape zonecapacity.SlotShape) *InstanceTypeStatic {
	capacity := tmpl.Capacity.DeepCopy()
	if capacity == nil {
		capacity = corev1.ResourceList{}
	}

	capacity[corev1.ResourceCPU] = *resource.NewQuantity(int64(shape.CPUs), resource.DecimalSI)
	capacity[corev1.ResourceMemory] = *resource.NewQuantity(int64(shape.Memory), resource.BinarySI)

	overhead := &cloudprovider.InstanceTypeOverhead{
		KubeReserved:      kubeReservedResources(&capacity),
		SystemReserved:    systemReservedResources(&capacity),
		EvictionThreshold: evictionThresholdResources(&capacity),
	}

	if tmpl.Overhead != nil {
		overhead = copyOverhead(tmpl.Overhead)
	}

	return &InstanceTypeStatic{
		Name:         name,
		Capacity:     capacity,
		CapacityType: tmpl.CapacityType,
		Overhead:     overhead,
		Offerings:    cloudprovider.Offerings{},
		NUMA:         tmpl.NUMA,
	}
}
